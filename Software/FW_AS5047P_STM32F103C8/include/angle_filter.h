/**
 * @file    angle_filter.h
 * @brief   Фильтр показаний магнитного энкодера: следящий наблюдатель угла
 *          второго порядка (angle tracking observer, он же цифровая ФАПЧ)
 *          с отбраковкой выбросов по невязке.
 *
 * Почему именно он (разбор публикаций — см. README, раздел «Фильтрация»):
 *
 *  - простое усреднение / БИХ-ФНЧ по углу даёт запаздывание, пропорциональное
 *    скорости: на постоянной скорости ошибка не исчезает, а растёт линейно
 *    с оборотами. Для датчика положения это худший вид ошибки;
 *  - следящий контур с ПИ-регулятором (тип II) имеет НУЛЕВУЮ установившуюся
 *    ошибку на линейно нарастающем угле, то есть при постоянной скорости
 *    фильтр не отстаёт вообще, при этом подавляя шум как ФНЧ 2-го порядка;
 *  - фильтр Калмана с той же моделью «постоянная скорость» в установившемся
 *    режиме вырождается ровно в такой же контур с постоянными коэффициентами,
 *    но требует матричных операций на каждом шаге. На Cortex-M3 без FPU это
 *    неоправданно: шум энкодера стационарен, адаптировать усиление не по чему;
 *  - побочная выгода: оценка скорости получается бесплатно и без численного
 *    дифференцирования (которое усиливает шум квантования).
 *
 * Шаг фильтра построен как «прогноз — невязка — коррекция» (как у Калмана,
 * но с постоянными коэффициентами):
 *
 *      theta = theta + Ts * omega               // прогноз на текущий такт
 *      e     = wrap(raw - theta)                // невязка (фазовый детектор)
 *      omega = omega + Ki * Ts * e              // коррекция скорости
 *      theta = theta + Kp * Ts * e              // коррекция угла
 *
 *      Kp = 2 * zeta * wn,   Ki = wn^2,   wn = 2*pi*f_bw
 *
 * Порядок важен: коррекция идёт ПОСЛЕ прогноза, поэтому после вызова
 * angle_filter_update() состояние относится к моменту только что принятого
 * измерения (а не к следующему такту), и «нулевое запаздывание на постоянной
 * скорости» выполняется буквально: измеренное смещение не выходит за 0.0001° на
 * скоростях до 12000 об/мин (tools/run_filter_model.sh, сценарий 1).
 *
 * Все величины — в отсчётах датчика (14 бит, 16384 на оборот) и отсчётах/с;
 * перевод в градусы делается только на выводе, чтобы не терять точность.
 */
#ifndef ANGLE_FILTER_H
#define ANGLE_FILTER_H

#include <stdint.h>
#include <stdbool.h>

#define ANGLE_FILTER_COUNTS      16384          /* отсчётов на оборот (14 бит) */
#define ANGLE_FILTER_HALF        8192           /* половина оборота */

/**
 * Рабочее ограничение полосы. При zeta = 1 явная (Эйлера) дискретизация
 * устойчива до wn*Ts = 2*sqrt(2)-2 ~ 0.83 (проверено прогоном: 0.825 с шагом
 * поиска 0.005, tools/run_filter_model.sh, п. 9.2). Рабочее значение берём
 * вчетверо меньше предела — это и есть запас.
 */
#define ANGLE_FILTER_WN_TS_MAX   0.2f

/**
 * Порог отбраковки по умолчанию, отсчёты. Невязка — это разность между
 * измерением и ПРОГНОЗОМ, поэтому на установившейся скорости она равна шуму
 * (единицы отсчётов) независимо от того, насколько быстро вращается вал.
 * Порог ограничивает не скорость, а мгновенный скачок: 512 отсчётов за такт
 * при 2 кГц — это рывок сразу до ~3750 об/мин, механически недостижимый.
 */
#define ANGLE_FILTER_GATE_DEFAULT       512

/** Сколько подряд забракованных отсчётов считать потерей захвата. */
#define ANGLE_FILTER_REJECT_LIMIT_DEF   16

typedef struct {
    /* --- настройки (вычисляет angle_filter_init) --- */
    float    ts;            /* период дискретизации, с */
    float    gain_p;        /* Kp * Ts, безразмерный */
    float    gain_i;        /* Ki * Ts, 1/с */
    float    bandwidth_hz;  /* фактическая полоса (после ограничения) */
    float    damping;       /* zeta */
    float    gate;          /* порог отбраковки невязки, отсчёты */
    uint32_t reject_limit;  /* подряд забракованных до перезахвата */

    /* --- состояние --- */
    float    theta;         /* оценка угла в обороте, отсчёты [0, 16384) */
    float    omega;         /* оценка скорости, отсчётов/с */
    int32_t  turns;         /* переходов через ноль С МОМЕНТА ЗАХВАТА, со знаком:
                               полное перемещение = turns*16384 + theta - theta(захват),
                               абсолютного многооборотного нуля у датчика нет */
    bool     locked;        /* контур захвачен */
    float    raw_prev;      /* предыдущий сырой отсчёт (для затравки скорости) */
    bool     have_prev;
    uint32_t reject_run;    /* текущая серия забракованных отсчётов */

    /* --- диагностика --- */
    int32_t  last_err;      /* последняя невязка (raw - прогноз), отсчёты */
    uint32_t n_update;      /* принятых отсчётов */
    uint32_t n_predict;     /* тактов, проведённых по модели (сбой чтения) */
    uint32_t n_gated;       /* отсчётов, забракованных порогом */
    uint32_t n_relock;      /* перезахватов после серии отбраковок */
} angle_filter_t;

/**
 * Настройка фильтра.
 *
 * @param sample_rate_hz  частота опроса датчика (должна быть постоянной!)
 * @param bandwidth_hz    желаемая полоса контура f_bw; будет ограничена
 *                        сверху значением angle_filter_max_bandwidth()
 * @param damping         zeta; 1.0 = критическое демпфирование (полюса
 *                        вещественные, колебаний нет). Выброс на скачке угла
 *                        это не убирает: ноль ветви Kp даёт ~10 % при 50 Гц
 */
void angle_filter_init(angle_filter_t *f, float sample_rate_hz,
                       float bandwidth_hz, float damping);

/** Порог отбраковки (отсчёты) и длина серии до перезахвата. 0 = не менять. */
void angle_filter_set_gate(angle_filter_t *f, float gate_counts, uint32_t reject_limit);

/** Сброс состояния: контур заново захватывается по следующим отсчётам. */
void angle_filter_reset(angle_filter_t *f);

/**
 * Такт с измерением: прогноз, невязка, отбраковка, коррекция.
 * Захват занимает два первых отсчёта — по их разности берётся начальная
 * скорость, поэтому фильтр стартует без «разгона» даже на вращающемся валу.
 */
void angle_filter_update(angle_filter_t *f, uint16_t raw);

/**
 * Такт без измерения (сбой SPI, ошибка чётности): ведём угол по модели
 * с последней оценкой скорости. Для следящего контура это естественно —
 * в отличие от «повторить прошлое значение», которое ломает оценку скорости.
 */
void angle_filter_predict(angle_filter_t *f);

/** Отфильтрованный угол, округлённый до отсчёта: 0..16383. */
uint16_t angle_filter_angle(const angle_filter_t *f);

/** Отфильтрованный угол в сотых долях градуса: 0..35999. */
uint32_t angle_filter_centideg(const angle_filter_t *f);

/** Оценка скорости в сотых долях градуса в секунду (со знаком). */
int32_t angle_filter_centideg_per_s(const angle_filter_t *f);

/** Оценка скорости в сотых долях оборота в минуту (со знаком). */
int32_t angle_filter_centirpm(const angle_filter_t *f);

/** Разность углов, приведённая к диапазону -8192..8191 отсчётов. */
int32_t angle_filter_wrap(int32_t diff);

/** Максимальная полоса, допустимая на данной частоте опроса, Гц. */
float angle_filter_max_bandwidth(float sample_rate_hz);

/**
 * Эквивалентная шумовая полоса контура, Гц: Bn = (wn / 2) * (zeta + 1/(4*zeta)),
 * wn = 2*pi*f_bw в рад/с (классическая формула Гарднера; при zeta = 1 это
 * Bn = 1.25*pi*f_bw, то есть почти в 4 раза ШИРЕ самой полосы f_bw).
 * Ожидаемое подавление белого шума измерения: sqrt(f_s / (2*Bn)) раз.
 */
float angle_filter_noise_bandwidth(const angle_filter_t *f);

#endif /* ANGLE_FILTER_H */
