/**
 * @file line_reader.h
 * @brief Универсальный помощник для разбора текстовых строк из кольцевого буфера.
 */

#ifndef LINE_READER_H
#define LINE_READER_H

#include <stdint.h>

/**
 * @brief Извлекает одну текстовую строку из программного кольцевого буфера.
 *
 * Алгоритм работы:
 * 1. Ищет символы конца строки (\\r или \\n).
 * 2. Поддерживает комбинации \\r, \\n, \\r\\n.
 * 3. Пустые строки (например, двойной \\n\\n) игнорируются.
 * 4. Если буфер заполнен полностью, но конца строки не найдено, индекс tail
 *    сдвигается ("slow-drain"), чтобы позволить новым данным войти в буфер.
 *
 * @param[in] ring Ссылка на кольцевой буфер.
 * @param[in] ring_size Размер буфера.
 * @param[in] head Текущий индекс записи.
 * @param[in,out] tail Указатель на индекс начала непрочитанных данных.
 * @param[out] buf Буфер для записи извлеченной строки.
 * @param[in] buf_size Размер выходного буфера.
 * @return Длина извлеченной строки (без \\0) или 0, если полная строка еще не принята.
 */
uint16_t line_reader_extract(const uint8_t *ring, uint16_t ring_size, 
                             uint16_t head, uint16_t *tail, 
                             char *buf, uint16_t buf_size);

#endif /* LINE_READER_H */
