/**
 * @file pid.h
 * @brief ПИД-регулятор для управления положением мотора.
 *
 * Описывает структуру состояния и функции для реализации классического
 * ПИД-регулирования с анти-виндапом (anti-windup).
 */

#ifndef PID_H
#define PID_H

#include <stdint.h>

/**
 * @brief Состояние ПИД-регулятора.
 */
typedef struct {
    float kp;               ///< Пропорциональный коэффициент
    float ki;               ///< Интегральный коэффициент
    float kd;               ///< Дифференциальный коэффициент
    float integral;         ///< Накопленная сумма ошибки (интегральная компонента)
    float prev_error;       ///< Ошибка на предыдущем шаге (для расчета производной)
    float output_min;       ///< Минимальное ограничение выхода (насыщение)
    float output_max;       ///< Максимальное ограничение выхода (насыщение)
    uint8_t initialized;    ///< Флаг первой итерации (чтобы избежать скачка производной)
} PID_State;

/* Сброс интеграла и prev_error */
void PID_Reset(PID_State *pid);

/* Обновление регулятора. error — текущая ошибка, dt — шаг по времени (с). */
float PID_Update(PID_State *pid, float error, float dt);

#endif /* PID_H */
